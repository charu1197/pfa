                btns.forEach(b => b.classList.remove('active'));
                this.classList.add('active');

                // Show/hide cards
                let visible = 0;
                cards.forEach(card => {
                    const match = filter === 'all' || card.dataset.category === filter;
                    card.style.display = match ? '' : 'none';
                    if (match) visible++;
                });

                noResults && (noResults.style.display = visible === 0 ? 'block' : 'none');
            });
        });
